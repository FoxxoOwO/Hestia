import { API_BASE, apiFetch, getHeaders, getAuthOnlyHeaders } from '../http';

export const authApi = {
  async verifyPassword(password: string): Promise<{ status: string }> {
    const res = await apiFetch(`${API_BASE}/auth/verify-password`, {
      method: 'POST',
      headers: getHeaders(),
      body: JSON.stringify({ password }),
    });
    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.detail || 'Nesprávné heslo');
    }
    return res.json();
  },

  async changePassword(currentPassword: string, newPassword: string): Promise<{ status: string; message: string }> {
    const res = await apiFetch(`${API_BASE}/auth/change-password`, {
      method: 'POST',
      headers: getHeaders(),
      body: JSON.stringify({ current_password: currentPassword, new_password: newPassword }),
    });
    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.detail || 'Nepodařilo se změnit heslo');
    }
    return res.json();
  },

  // Public members for login
  async getPublicMembers(): Promise<PublicMember[]> {
    const res = await apiFetch(`${API_BASE}/auth/public-members`);
    if (!res.ok) throw new Error('Failed to fetch household members');
    return res.json();
  },

};
